-- Cùng SQL chạy trên PostgreSQL production và H2 ở local/test.
-- JDBC được dùng để nhìn rõ câu SQL và ranh giới transaction khi học.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(24) NOT NULL UNIQUE,
    display_name VARCHAR(30) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE,
    name VARCHAR(40) NOT NULL,
    host_user_id BIGINT NOT NULL REFERENCES users(id),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 2 AND 4),
    status VARCHAR(16) NOT NULL CHECK (status IN ('WAITING','RUNNING','RECOVERING','CLOSED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Chỉ giữ membership hiện tại. user_id là PK nên không thể chiếm hai phòng.
-- Lịch sử tham gia trận nằm ở match_players, không bị xóa khi rời phòng.
CREATE TABLE room_players (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    seat INTEGER NOT NULL CHECK (seat BETWEEN 0 AND 3),
    ready BOOLEAN NOT NULL DEFAULT FALSE,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(room_id, seat)
);
CREATE INDEX idx_room_players_room ON room_players(room_id);
CREATE TABLE matches (
    id VARCHAR(36) PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('RUNNING','RECOVERING','FINISHED','ABORTED')),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP WITH TIME ZONE,
    recovery_deadline_at TIMESTAMP WITH TIME ZONE,
    winner_user_id BIGINT REFERENCES users(id),
    end_reason VARCHAR(60),
    rules_version INTEGER NOT NULL
);
CREATE INDEX idx_matches_room_status ON matches(room_id,status);
CREATE TABLE match_players (
    match_id VARCHAR(36) NOT NULL REFERENCES matches(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    seat INTEGER NOT NULL,
    outcome VARCHAR(8),
    final_hp INTEGER,
    forfeited_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(match_id,user_id)
);
CREATE INDEX idx_match_players_user ON match_players(user_id);
-- payload chứa cả map/rules và state. TEXT giữ định dạng JSON rõ ràng, portable.
CREATE TABLE match_snapshots (
    match_id VARCHAR(36) PRIMARY KEY REFERENCES matches(id),
    schema_version INTEGER NOT NULL,
    tick BIGINT NOT NULL,
    payload TEXT NOT NULL,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

